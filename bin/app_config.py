"""Single source of infrastructure configuration for the Clinic Booking consumer.

The published sigmoid_cdk package owns all CDK constructs and security defaults.
This file declares resources, seven handlers, dependencies, and per-function runtimes.
"""

import os
import re
from datetime import date

from sigmoid_cdk.configs import (
    ApiGatewayConfig,
    ApiRouteConfig,
    CloudFrontConfig,
    EventRuleConfig,
    IndexConfig,
    LambdaConfig,
    QueueConfig,
    ResourceConfig,
    S3Config,
    TableConfig,
)

# --- Application identity ---
APP_NAME = "clinic-booking"
OWNER_TEAM = "clinic-team"
COST_CENTER = "cc-100"
BUCKET_SUFFIX = os.getenv("BUCKET_SUFFIX", "demo")
SENDER_EMAIL = os.getenv("SENDER_EMAIL", "").strip() or "clinic@example.com"
HOLIDAY_DATES = os.getenv("CLINIC_HOLIDAYS", "").strip()



# --- Extra S3 buckets (optional) ---
# Example: ADDITIONAL_BUCKETS = ("reports", "private-assets")
# Empty by default to preserve the original audited 1-bucket architecture.
ADDITIONAL_BUCKETS: tuple[str, ...] = ()

# --- Lambda defaults and individual overrides ---
LAMBDA_SOURCE = "src/backend"
DEFAULT_RUNTIME = "PYTHON_3_14"
DEFAULT_MEMORY_MB = 256
DEFAULT_TIMEOUT_SECONDS = 20

# Different functions may use different runtimes when compatible code exists.

LAMBDA_RUNTIMES: dict[str, str] = {   
    # "node-reports": "NODEJS_22_X",
    # "java-reports": "JAVA_21",
}
LAMBDA_SOURCES: dict[str, str] = { 
    # "node-reports": "src/node-reports",
    # "java-reports": "src/java-reports/dist",
}  # for different language/source packages


LAMBDA_HANDLERS: dict[str, str] = {

    # "node-reports": "index.handler",
}  # full handler, e.g. index.handler




ROUTES = (
    ("GET", "api/slots", "list-slots"),
    ("POST", "api/bookings", "book-slot"),
    ("GET", "api/bookings/{code}", "get-booking"),
    ("DELETE", "api/bookings/{code}", "cancel-booking"),
    ("GET", "api/staff/today", "staff-today"),
)


def create_lambda(
    name: str,
    handler: str,
    *,
    queue: bool = False,
    email: bool = False,
    timeout: int = DEFAULT_TIMEOUT_SECONDS,
) -> LambdaConfig:
    """Define exactly one function; grants are generated by sigmoid_cdk."""
    return LambdaConfig(
        function_name=name,
        entry_point_dir=LAMBDA_SOURCES.get(name, LAMBDA_SOURCE),
        handler=LAMBDA_HANDLERS.get(name, f"clinic.{handler}"),
        runtime=LAMBDA_RUNTIMES.get(name, DEFAULT_RUNTIME),
        memory_mb=DEFAULT_MEMORY_MB,
        timeout_seconds=timeout,
        environment_vars={
            "APP_MODE": "aws",  # staff API fails closed without authentication
            "CLINIC_HOLIDAYS": HOLIDAY_DATES,
        },
        read_write_tables=["bookings"],
        send_to_queues=["booking-events"] if queue else [],
        send_email_from=SENDER_EMAIL if email else None,
    )


def build_config(stage: str) -> ResourceConfig:
    """Build the infrastructure description; no AWS calls are made here."""
    if stage not in {"dev", "staging", "prod"}:
        raise ValueError("STAGE must be dev, staging or prod")
    if not re.fullmatch(r"[a-z0-9]{2,24}", BUCKET_SUFFIX):
        raise ValueError("BUCKET_SUFFIX must contain 2–24 lowercase letters/digits")
    for holiday in HOLIDAY_DATES.split(","):
        if holiday.strip():
            date.fromisoformat(holiday.strip())

    for purpose in ADDITIONAL_BUCKETS:
        if not re.fullmatch(r"[a-z][a-z0-9-]{1,22}", purpose):
            raise ValueError(f"Invalid additional S3 bucket purpose: {purpose!r}")

    return ResourceConfig(
        app_name=APP_NAME,
        environment=stage,
        owner_team=OWNER_TEAM,
        cost_center=COST_CENTER,

        frontend_bucket=S3Config(
            bucket_name=f"{APP_NAME}-web-{stage}-{BUCKET_SUFFIX}"
        ),
        extra_buckets=[
            S3Config(bucket_name=f"{APP_NAME}-{purpose}-{stage}-{BUCKET_SUFFIX}")
    
            for purpose in ADDITIONAL_BUCKETS
        ],



        cloudfront=CloudFrontConfig(
            api_name="clinic-api", default_root_object="index.html"
        ),



        tables=[
            TableConfig(
                table_name="bookings",
                partition_key="booking_date",
                sort_key="slot_time",
                indexes=[
                    IndexConfig(index_name="code-index", partition_key="booking_code")
                ],
                ttl_attribute="expires_at",
            )
        ],
        lambdas=[
            create_lambda("list-slots", "list_slots"),
            create_lambda("book-slot", "book_slot", queue=True),
            create_lambda("get-booking", "get_booking"),
            create_lambda("cancel-booking", "cancel_booking", queue=True),
            create_lambda("staff-today", "staff_today"),
            create_lambda("notify-worker", "notify_worker", email=True, timeout=30),
            # daily_reminder() sends mail itself; it needs SES permission too.
            create_lambda("daily-reminder", "daily_reminder", email=True, timeout=60),

            # create_lambda("node-reports", "handler"),
        ],
        api_gateways=[
            ApiGatewayConfig(
                api_name="clinic-api",
                stage_name="v1",
                rate_limit=10,
                burst_limit=20,
                routes=[
                    ApiRouteConfig(path=path, http_method=method, lambda_name=name)
                    for method, path, name in ROUTES
                ],
            )
        ],
        queues=[
            QueueConfig(
                queue_name="booking-events",
                consumer_lambda="notify-worker",
                batch_size=1,
            )
        ],
        event_rules=[
            EventRuleConfig(
                rule_name="daily-reminder-schedule",
                description="Daily reminder at 09:00 Asia/Kolkata (03:30 UTC)",
                schedule_expression="cron(30 3 * * ? *)",
                target_lambda="daily-reminder",
            )
        ],
    )